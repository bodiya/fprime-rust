#[cfg(test)]
mod tests {
    use super::*;

    /// The canonical CRC-16/CCITT-FALSE check value.
    #[test]
    fn check_value_of_123456789() {
        assert_eq!(Crc16::compute(b"123456789"), 0x29B1);
    }

    /// The empty message returns the initial value unchanged.
    #[test]
    fn empty_input_is_init_value() {
        assert_eq!(Crc16::compute(&[]), 0xFFFF);
        assert_eq!(Crc16::new().finalize(), 0xFFFF);
    }

    /// Published CRC-16/CCITT-FALSE vectors (cross-checked against an
    /// independent implementation).
    #[test]
    fn literal_vectors() {
        assert_eq!(Crc16::compute(&[0x00]), 0xE1F0);
        assert_eq!(Crc16::compute(&[0x00, 0x00]), 0x1D0F);
        assert_eq!(Crc16::compute(&[0xFF]), 0xFF00);
        assert_eq!(Crc16::compute(&[0xA5]), 0x04BF);
        assert_eq!(Crc16::compute(b"A"), 0xB915);
        assert_eq!(Crc16::compute(b"CCSDS"), 0xB7F6);
        assert_eq!(Crc16::compute(&[0x01, 0x02, 0x03, 0x04]), 0x89C3);
    }

    /// Streaming byte-by-byte equals the one-shot computation (the frame
    /// detector peeks a ring buffer one byte at a time).
    #[test]
    fn streaming_matches_one_shot() {
        let data: Vec<u8> = (0u8..=255).collect();
        let mut crc = Crc16::new();
        for &byte in &data {
            crc.update(byte);
        }
        assert_eq!(crc.finalize(), Crc16::compute(&data));
    }

    /// Appending the big-endian CRC to a message makes the CRC of the whole
    /// message zero — the property the CCSDS FECF relies on.
    #[test]
    fn appending_crc_yields_zero_residue() {
        let mut msg = b"CCSDS TM FRAME".to_vec();
        let crc = Crc16::compute(&msg);
        msg.extend_from_slice(&crc.to_be_bytes());
        assert_eq!(Crc16::compute(&msg), 0x0000);
    }

    /// The table is the MSB-first 0x1021 table (spot values).
    #[test]
    fn table_entries_match_polynomial() {
        assert_eq!(TABLE[0], 0x0000);
        assert_eq!(TABLE[1], 0x1021);
        assert_eq!(TABLE[2], 0x2042);
        assert_eq!(TABLE[255], 0x1EF0);
    }

    /// `finalize` is non-mutating (C++ parity: the register survives).
    #[test]
    fn finalize_does_not_consume_state() {
        let mut crc = Crc16::new();
        crc.update_all(b"1234");
        let first = crc.finalize();
        assert_eq!(first, crc.finalize());
        crc.update_all(b"56789");
        assert_eq!(crc.finalize(), 0x29B1);
        assert_eq!(crc.register(), 0x29B1);
    }
}
