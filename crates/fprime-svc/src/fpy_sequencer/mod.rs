    /// `LogFatal` … `LogDiagnostic`: the `POP_EVENT` events, one per
    /// severity, all `Sequence {}: {}`.
    fn log_sequence_message(&self, severity: LogSeverity, file_path: &[u8], message: &[u8]) {
        let id = match severity {
            LogSeverity::Fatal => Self::EVENTID_LOG_FATAL,
            LogSeverity::WarningHi => Self::EVENTID_LOG_WARNING_HI,
            LogSeverity::WarningLo => Self::EVENTID_LOG_WARNING_LO,
            LogSeverity::Command => Self::EVENTID_LOG_COMMAND,
            LogSeverity::ActivityHi => Self::EVENTID_LOG_ACTIVITY_HI,
            LogSeverity::ActivityLo => Self::EVENTID_LOG_ACTIVITY_LO,
            LogSeverity::Diagnostic => Self::EVENTID_LOG_DIAGNOSTIC,
        };
        self.log(
            id,
            severity,
            format_args!("Sequence {}: {}", Lossy(file_path), Lossy(message)),
            |b| {
                fw_try!(ser_str(b, file_path));
                ser_str(b, message)
            },
        );
    }
