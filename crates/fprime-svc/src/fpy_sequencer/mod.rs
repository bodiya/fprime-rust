#[allow(non_snake_case)]
impl Handlers for FpySequencer {
    /// Raise `entered`.
    fn action_signalEntered(&self, _sm_id: FwEnumStoreType, _signal: Signal) {
        self.sm().send_signal_entered();
    }

    /// Resolve the file path against `SEQ_BASE_DIR` (`<base>/<file>`).
    fn action_setSequenceFilePath(
        &self,
        _sm_id: FwEnumStoreType,
        _signal: Signal,
        value: &SequenceExecutionArgs,
    ) {
        let (base_dir, _valid) = self.param_get_seq_base_dir();
        let mut st = self.state.lock().unwrap();
        if base_dir.is_empty() {
            st.sequence_file_path = value.file_path.clone();
            return;
        }
        // C++ `format("%s/%s")` into the 240-byte path: truncated at the
        // capacity, which is the only runtime-reachable failure (OVERFLOWED).
        let needed = base_dir.len() + 1 + value.file_path.len();
        let path = &mut st.sequence_file_path;
        path.set_bytes(base_dir.as_bytes());
        path.append_bytes(b"/");
        path.append_bytes(value.file_path.as_bytes());
        drop(st);
        if needed > FileNameString::CAPACITY {
            self.log_warning_hi_sequence_file_path_too_long(
                base_dir.as_bytes(),
                value.file_path.as_bytes(),
            );
        }
    }

    fn action_setSequenceBlockState(
        &self,
        _sm_id: FwEnumStoreType,
        _signal: Signal,
        value: &SequenceExecutionArgs,
    ) {
        self.state.lock().unwrap().sequence_block_state = value.block;
    }

    fn action_setSequenceArguments(
        &self,
        _sm_id: FwEnumStoreType,
        _signal: Signal,
        value: &SequenceExecutionArgs,
    ) {
        self.state.lock().unwrap().sequence_args = value.buffer;
    }

    /// Run validation and raise `result_success` / `result_failure`.
    fn action_validate(&self, _sm_id: FwEnumStoreType, _signal: Signal) {
        let result = {
            let mut st = self.state.lock().unwrap();
            self.validate(&mut st)
        };
        if result == fprime_fw::Success::Failure {
            self.sm().send_signal_result_failure();
            return;
        }
        self.sm().send_signal_result_success();
    }

    fn action_report_seqSucceeded(&self, _sm_id: FwEnumStoreType, _signal: Signal) {
        {
            let mut st = self.state.lock().unwrap();
            st.tlm.sequences_succeeded += 1;
            self.log_activity_hi_sequence_done(st.sequence_file_path.as_bytes());
            st.sequence_file_path.set(NO_SEQ);
        }
        if let Some(p) = self.seq_done_out.try_get() {
            p.target.invoke(p.port_num, 0, 0, CmdResponse::Ok);
        }
    }

    fn action_report_seqCancelled(&self, _sm_id: FwEnumStoreType, _signal: Signal) {
        {
            let mut st = self.state.lock().unwrap();
            st.tlm.sequences_cancelled += 1;
            self.log_activity_hi_sequence_cancelled(st.sequence_file_path.as_bytes());
        }
        if let Some(p) = self.seq_done_out.try_get() {
            p.target
                .invoke(p.port_num, 0, 0, CmdResponse::ExecutionError);
        }
    }

    fn action_report_seqFailed(&self, _sm_id: FwEnumStoreType, _signal: Signal) {
        if let Some(p) = self.seq_done_out.try_get() {
            p.target
                .invoke(p.port_num, 0, 0, CmdResponse::ExecutionError);
        }
    }

    fn action_report_seqStarted(&self, _sm_id: FwEnumStoreType, _signal: Signal) {
        if let Some(p) = self.seq_start_out.try_get() {
            // C++ note: the arguments are empty when validation was
            // requested with VALIDATE rather than RUN.
            let (path, args) = {
                let st = self.state.lock().unwrap();
                (st.sequence_file_path.clone(), st.sequence_args)
            };
            p.target.invoke(p.port_num, &path, &args);
        }
    }

    fn action_setGoalState_RUNNING(&self, _sm_id: FwEnumStoreType, _signal: Signal) {
        self.state.lock().unwrap().goal_state = GoalState::Running;
    }

    fn action_setGoalState_VALID(&self, _sm_id: FwEnumStoreType, _signal: Signal) {
        self.state.lock().unwrap().goal_state = GoalState::Valid;
    }

    fn action_setGoalState_IDLE(&self, _sm_id: FwEnumStoreType, _signal: Signal) {
        self.state.lock().unwrap().goal_state = GoalState::Idle;
    }

    fn action_sendCmdResponse_OK(&self, _sm_id: FwEnumStoreType, _signal: Signal) {
        let (block, op_code, cmd_seq) = self.saved_response();
        if block == BlockState::Block {
            self.cmd.cmd_response(op_code, cmd_seq, CmdResponse::Ok);
        }
    }

    fn action_sendCmdResponse_EXECUTION_ERROR(&self, _sm_id: FwEnumStoreType, _signal: Signal) {
        let (block, op_code, cmd_seq) = self.saved_response();
        if block == BlockState::Block {
            self.cmd
                .cmd_response(op_code, cmd_seq, CmdResponse::ExecutionError);
        }
    }

    fn action_clearSequenceFile(&self, _sm_id: FwEnumStoreType, _signal: Signal) {
        self.state.lock().unwrap().sequence_file_path.clear();
    }

    fn action_clearBreakpoint(&self, _sm_id: FwEnumStoreType, _signal: Signal) {
        self.state.lock().unwrap().breakpoint = BreakpointInfo::default();
    }

    fn action_clearSequenceArguments(&self, _sm_id: FwEnumStoreType, _signal: Signal) {
        self.state.lock().unwrap().sequence_args = SeqArgs::default();
    }

    fn action_checkShouldWake(&self, _sm_id: FwEnumStoreType, _signal: Signal) {
        let result = {
            let st = self.state.lock().unwrap();
            self.check_should_wake(&st)
        };
        match result {
            Signal::result_checkShouldWake_keepSleeping => {
                self.sm().send_signal_result_checkShouldWake_keepSleeping();
            }
            Signal::result_checkShouldWake_wakeup => {
                self.sm().send_signal_result_checkShouldWake_wakeup();
            }
            Signal::result_timeOpFailed => self.sm().send_signal_result_timeOpFailed(),
            other => fw_assert!(false, other.as_repr()),
        }
    }

    fn action_dispatchStatement(&self, _sm_id: FwEnumStoreType, _signal: Signal) {
        let result = {
            let mut st = self.state.lock().unwrap();
            self.dispatch_statement(&mut st)
        };
        match result {
            Signal::result_dispatchStatement_noMoreStatements => {
                self.sm()
                    .send_signal_result_dispatchStatement_noMoreStatements();
            }
            Signal::result_dispatchStatement_success => {
                self.sm().send_signal_result_dispatchStatement_success();
            }
            Signal::result_dispatchStatement_failure => {
                self.sm().send_signal_result_dispatchStatement_failure();
            }
            other => fw_assert!(false, other.as_repr()),
        }
    }

    fn action_resetRuntime(&self, _sm_id: FwEnumStoreType, _signal: Signal) {
        self.state.lock().unwrap().runtime.reset();
    }

    fn action_checkStatementTimeout(&self, _sm_id: FwEnumStoreType, _signal: Signal) {
        let result = {
            let st = self.state.lock().unwrap();
            self.check_statement_timeout(&st)
        };
        match result {
            Signal::result_checkStatementTimeout_noTimeout => {
                self.sm()
                    .send_signal_result_checkStatementTimeout_noTimeout();
            }
            Signal::result_checkStatementTimeout_statementTimeout => {
                self.sm()
                    .send_signal_result_checkStatementTimeout_statementTimeout();
            }
            Signal::result_timeOpFailed => self.sm().send_signal_result_timeOpFailed(),
            other => fw_assert!(false, other.as_repr()),
        }
    }

    fn action_incrementSequenceCounter(&self, _sm_id: FwEnumStoreType, _signal: Signal) {
        self.state.lock().unwrap().sequences_started += 1;
    }

    /// Push the sequence arguments (already big-endian F Prime
    /// serialization) onto the fresh stack.
    fn action_pushArgsToStack(&self, _sm_id: FwEnumStoreType, _signal: Signal) {
        let mut guard = self.state.lock().unwrap();
        let st = &mut *guard;
        let size = st.sequence_args.size;
        if size == 0 {
            return;
        }
        // validate() rejected any size above the buffer's capacity
        let size = size as usize;
        fw_assert!(size <= st.sequence_args.buffer.0.len(), size as i32);
        st.runtime
            .stack
            .push_bytes(&st.sequence_args.buffer.0[..size]);
    }

    fn action_report_seqBroken(&self, _sm_id: FwEnumStoreType, _signal: Signal) {
        let index = self.state.lock().unwrap().runtime.next_statement_index;
        self.log_activity_hi_sequence_paused(index);
    }

    fn action_setBreakpoint(
        &self,
        _sm_id: FwEnumStoreType,
        _signal: Signal,
        value: &BreakpointArgs,
    ) {
        {
            let mut st = self.state.lock().unwrap();
            st.breakpoint.breakpoint_in_use = value.break_on_breakpoint;
            st.breakpoint.break_only_once_on_breakpoint = value.break_only_once_on_breakpoint;
            st.breakpoint.breakpoint_index = value.breakpoint_index;
        }
        self.log_activity_hi_breakpoint_set(
            value.breakpoint_index,
            value.break_only_once_on_breakpoint,
        );
    }

    fn action_setBreakBeforeNextLine(&self, _sm_id: FwEnumStoreType, _signal: Signal) {
        self.state.lock().unwrap().breakpoint.break_before_next_line = true;
    }

    fn action_clearBreakBeforeNextLine(&self, _sm_id: FwEnumStoreType, _signal: Signal) {
        self.state.lock().unwrap().breakpoint.break_before_next_line = false;
    }

    fn guard_goalStateIs_RUNNING(&self, _sm_id: FwEnumStoreType, _signal: Signal) -> bool {
        self.state.lock().unwrap().goal_state == GoalState::Running
    }

    /// Break before the next statement: the "break on next line" flag, or
    /// the breakpoint at the next statement index.
    fn guard_shouldBreak(&self, _sm_id: FwEnumStoreType, _signal: Signal) -> bool {
        let st = self.state.lock().unwrap();
        st.breakpoint.break_before_next_line
            || (st.breakpoint.breakpoint_in_use
                && st.breakpoint.breakpoint_index == st.runtime.next_statement_index)
    }

    fn guard_breakOnce(&self, _sm_id: FwEnumStoreType, _signal: Signal) -> bool {
        self.state
            .lock()
            .unwrap()
            .breakpoint
            .break_only_once_on_breakpoint
    }
}

