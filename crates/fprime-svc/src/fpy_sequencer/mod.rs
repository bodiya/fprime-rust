/// The sequence file buffer (C++ `m_sequenceBuffer`, an
/// `Fw::ExternalSerializeBuffer` over memory from `allocateBuffer`): one
/// stage of the file at a time is read into its start.
#[derive(Debug, Default)]
pub struct SequenceBuffer {
    data: Box<[u8]>,
    ser: usize,
    deser: usize,
}

impl SequenceBuffer {
    /// C++ `setExtBuffer`: replace the storage with `bytes` zeroed bytes
    /// and reset both cursors.
    pub fn set_ext_buffer(&mut self, bytes: usize) {
        self.data = vec![0u8; bytes].into_boxed_slice();
        self.ser = 0;
        self.deser = 0;
    }

    /// C++ `clear`: drop the storage.
    pub fn clear(&mut self) {
        self.data = Box::default();
        self.ser = 0;
        self.deser = 0;
    }

    /// True when storage has been allocated (C++ `getBuffAddr() != nullptr`).
    #[must_use]
    pub fn is_allocated(&self) -> bool {
        !self.data.is_empty()
    }
}

impl SerBufAny for SequenceBuffer {
    fn bytes(&self) -> &[u8] {
        &self.data
    }
    fn bytes_mut(&mut self) -> &mut [u8] {
        &mut self.data
    }
    fn capacity(&self) -> usize {
        self.data.len()
    }
    fn ser_loc(&self) -> usize {
        self.ser
    }
    fn set_ser_loc(&mut self, loc: usize) {
        self.ser = loc;
    }
    fn deser_loc(&self) -> usize {
        self.deser
    }
    fn set_deser_loc(&mut self, loc: usize) {
        self.deser = loc;
    }
    fn as_ser_buf_any(&mut self) -> &mut dyn SerBufAny {
        self
    }
}

/// The time to wake up at (C++ `Runtime::wakeupTime`), kept as the raw
/// fields: `WAIT_ABS` builds it from four stack values, and the C++
/// `Fw::Time` holds whatever time base the sequence pushed, even one that
/// is not a declared `TimeBase` (which then never matches the current time
/// base). The Rust `TimeBase` enum cannot hold such a value.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct WakeupTime {
    /// The time base, as stored.
    pub time_base: FwTimeBaseStoreType,
    /// The time context.
    pub time_context: FwTimeContextStoreType,
    /// Seconds.
    pub seconds: u32,
    /// Microseconds (always below 1,000,000).
    pub useconds: u32,
}

impl From<Time> for WakeupTime {
    fn from(time: Time) -> Self {
        Self {
            time_base: time.get_time_base().as_repr(),
            time_context: time.get_context(),
            seconds: time.get_seconds(),
            useconds: time.get_useconds(),
        }
    }
}

/// C++ `FpySequencer::Runtime`: everything needed to run the sequence.
#[derive(Debug)]
pub struct Runtime {
    /// The index of the next statement to be executed.
    pub next_statement_index: u32,
    /// The opcode of the statement that is currently executing.
    pub current_statement_opcode: u8,
    /// The opcode of the command being awaited, or 0 for a directive.
    pub current_cmd_opcode: FwOpcodeType,
    /// When the current statement was dispatched.
    pub current_statement_dispatch_time: Time,
    /// The absolute time to wake up at.
    pub wakeup_time: WakeupTime,
    /// The `SET_SEED` / `PUSH_RAND` generator.
    pub rng: Mt19937,
    /// Whether `rng` has been seeded in this run.
    pub rng_seeded: bool,
    /// The sequence stack.
    pub stack: Stack,
}

impl Runtime {
    fn new() -> Self {
        Self {
            next_statement_index: 0,
            current_statement_opcode: DirectiveId::Invalid.as_repr(),
            current_cmd_opcode: 0,
            current_statement_dispatch_time: Time::default(),
            wakeup_time: WakeupTime::default(),
            rng: Mt19937::new(),
            rng_seeded: false,
            stack: Stack::new(),
        }
    }

    /// C++ `resetRuntime`: destroy and reconstruct the runtime (here in
    /// place, without reallocating the stack).
    pub fn reset(&mut self) {
        self.next_statement_index = 0;
        self.current_statement_opcode = DirectiveId::Invalid.as_repr();
        self.current_cmd_opcode = 0;
        self.current_statement_dispatch_time = Time::default();
        self.wakeup_time = WakeupTime::default();
        self.rng = Mt19937::new();
        self.rng_seeded = false;
        self.stack.reset();
    }
}

