impl FpySequencer {
    /// Construct (C++ constructor). Allocates the sequence storage and the
    /// stack (about 1.1 MiB with the default configuration). Follow with
    /// `set_id_base`, wiring, [`Self::init`], [`Self::allocate_buffer`],
    /// [`Self::reg_commands`], [`Self::load_parameters`] and `active.start`.
    #[must_use]
    pub fn new(name: &str) -> Arc<Self> {
        let mut seq_base_dir = ParamString::new();
        seq_base_dir.set(fprime_config::fpy_sequencer::DEFAULT_SEQ_BASE_DIR);
        Arc::new(Self {
            active: ActiveBase::new(name),
            cmd: CmdGlue::new(),
            evt: EventGlue::new(),
            tlm: TlmGlue::new(),
            prm: PrmGlue::new(),
            cmd_out: OutputPort::new(),
            seq_start_out: OutputPort::new(),
            seq_done_out: OutputPort::new(),
            ping_out: OutputPort::new(),
            get_tlm_chan: OutputPort::new(),
            get_param: OutputPort::new(),
            serial_out: std::array::from_fn(|_| OutputPort::new()),
            sequencer: StateMachine::new(),
            state: Mutex::new(FpyState::new()),
            params: Mutex::new(FpyParams {
                statement_timeout_secs: Self::STATEMENT_TIMEOUT_SECS_DEFAULT,
                statement_timeout_secs_valid: ParamValid::Uninit,
                seq_base_dir,
                seq_base_dir_valid: ParamValid::Uninit,
            }),
            tlm_last: Mutex::new(TlmLast::default()),
        })
    }

    /// C++ `init(queueDepth, instance)`: initialize the state machine (its
    /// initial transition enters `IDLE`), then create the queue — in that
    /// order, as the generated code does.
    pub fn init(&self, queue_depth: FwSizeType) {
        self.sequencer.init(Self::SM_ID_SEQUENCER, self);
        self.active
            .queued
            .create_queue(queue_depth, QUEUE_MSG_SIZE as FwSizeType);
    }

    fn id_base(&self) -> FwIdType {
        self.active.queued.base.get_id_base()
    }

    /// C++ `regCommands()`: the twelve commands and the four parameter
    /// commands.
    pub fn reg_commands(&self) {
        self.cmd.reg_commands(
            self.id_base(),
            &[
                Self::OPCODE_RUN,
                Self::OPCODE_RUN_ARGS,
                Self::OPCODE_VALIDATE,
                Self::OPCODE_VALIDATE_ARGS,
                Self::OPCODE_RUN_VALIDATED,
                Self::OPCODE_CANCEL,
                Self::OPCODE_SET_BREAKPOINT,
                Self::OPCODE_BREAK,
                Self::OPCODE_CONTINUE,
                Self::OPCODE_CLEAR_BREAKPOINT,
                Self::OPCODE_STEP,
                Self::OPCODE_DUMP_STACK_TO_FILE,
                Self::OPCODE_STATEMENT_TIMEOUT_SECS_PRM_SET,
                Self::OPCODE_STATEMENT_TIMEOUT_SECS_PRM_SAVE,
                Self::OPCODE_SEQ_BASE_DIR_PRM_SET,
                Self::OPCODE_SEQ_BASE_DIR_PRM_SAVE,
            ],
        );
    }

    /// C++ `allocateBuffer(identifier, allocator, bytes)`: the buffer the
    /// file is read into, one stage (header, body, footer) at a time, so it
    /// must hold the largest body. Asserts that it holds at least a header.
    pub fn allocate_buffer(&self, identifier: FwEnumStoreType, bytes: FwSizeType) {
        // C++ parity: the buffer must fit a header.
        fw_assert!(bytes >= Header::SERIALIZED_SIZE as FwSizeType, bytes as i32);
        let mut st = self.state.lock().unwrap();
        st.allocator_id = identifier;
        st.sequence_buffer.set_ext_buffer(bytes as usize);
    }

    /// C++ `deallocateBuffer(allocator)`.
    pub fn deallocate_buffer(&self) {
        self.state.lock().unwrap().sequence_buffer.clear();
    }

    /// The state of the sequencer (C++ `sequencer_getState`).
    #[must_use]
    pub fn sequencer_get_state(&self) -> State {
        self.sequencer.get_state()
    }

    /// C++ `isRunningState`: true for the substates of `RUNNING`.
    #[must_use]
    pub fn is_running_state(state: State) -> bool {
        matches!(
            state,
            State::RUNNING_AWAITING_STATEMENT_RESPONSE
                | State::RUNNING_DISPATCH_STATEMENT
                | State::RUNNING_PAUSED
                | State::RUNNING_SLEEPING
        )
    }

    /// The signal sender of the `sequencer` instance (C++
    /// `sequencer_sendSignal_*`).
    fn sm(&self) -> Sender<'_, QUEUE_MSG_SIZE> {
        Sender(SmSender::new(
            &self.active.queued,
            Self::MSG_TYPE_INTERNAL_STATE_MACHINE_SIGNAL,
            Self::SM_ID_SEQUENCER,
            SM_PRIORITY,
            QueueFullPolicy::Assert,
        ))
    }

    /// C++ `sendSignal`: forward a directive handler's statement response.
    fn send_signal(&self, signal: Signal) {
        match signal {
            Signal::stmtResponse_beginSleep => self.sm().send_signal_stmtResponse_beginSleep(),
            Signal::stmtResponse_success => self.sm().send_signal_stmtResponse_success(),
            Signal::stmtResponse_failure => self.sm().send_signal_stmtResponse_failure(),
            Signal::stmtResponse_keepWaiting => self.sm().send_signal_stmtResponse_keepWaiting(),
            other => fw_assert!(false, other.as_repr()),
        }
    }

    // -- Parameters ----------------------------------------------------------

    /// `paramGet_STATEMENT_TIMEOUT_SECS`.
    #[must_use]
    pub fn param_get_statement_timeout_secs(&self) -> (f32, ParamValid) {
        let params = self.params.lock().unwrap();
        (
            params.statement_timeout_secs,
            params.statement_timeout_secs_valid,
        )
    }

    /// `paramGet_SEQ_BASE_DIR`.
    #[must_use]
    pub fn param_get_seq_base_dir(&self) -> (ParamString, ParamValid) {
        let params = self.params.lock().unwrap();
        (params.seq_base_dir.clone(), params.seq_base_dir_valid)
    }

    /// The generated `loadParameters()`: fetch both parameters through
    /// `prmGet` (which must be connected), install the FPP default when a
    /// value is not `VALID` or does not deserialize, then call
    /// `parametersLoaded`.
    pub fn load_parameters(&self) {
        let id_base = self.id_base();
        let mut buf = ParamBuffer::new();
        let valid = self
            .prm
            .get_param(id_base, Self::PARAMID_STATEMENT_TIMEOUT_SECS, &mut buf);
        let mut timeout = 0f32;
        let timeout_ok = valid == ParamValid::Valid && buf.deserialize_f32_be(&mut timeout).is_ok();

        let mut buf = ParamBuffer::new();
        let valid = self
            .prm
            .get_param(id_base, Self::PARAMID_SEQ_BASE_DIR, &mut buf);
        let mut base_dir = ParamString::new();
        let base_dir_ok =
            valid == ParamValid::Valid && buf.deserialize(&mut base_dir, Endianness::Big).is_ok();
        {
            let mut params = self.params.lock().unwrap();
            if timeout_ok {
                params.statement_timeout_secs = timeout;
                params.statement_timeout_secs_valid = ParamValid::Valid;
            } else {
                params.statement_timeout_secs = Self::STATEMENT_TIMEOUT_SECS_DEFAULT;
                params.statement_timeout_secs_valid = ParamValid::Default;
            }
            if base_dir_ok {
                params.seq_base_dir = base_dir;
                params.seq_base_dir_valid = ParamValid::Valid;
            } else {
                params
                    .seq_base_dir
                    .set(fprime_config::fpy_sequencer::DEFAULT_SEQ_BASE_DIR);
                params.seq_base_dir_valid = ParamValid::Default;
            }
        }
        self.parameters_loaded();
    }

    /// C++ `parametersLoaded`.
    fn parameters_loaded(&self) {
        self.parameter_updated(Self::PARAMID_STATEMENT_TIMEOUT_SECS);
        self.parameter_updated(Self::PARAMID_SEQ_BASE_DIR);
    }

    /// C++ `parameterUpdated`: echo the parameter on its telemetry channel.
    /// Asserts that the value is usable (`FW_PARAM_OK`).
    fn parameter_updated(&self, id: FwPrmIdType) {
        let valid = match id {
            Self::PARAMID_STATEMENT_TIMEOUT_SECS => {
                let (value, valid) = self.param_get_statement_timeout_secs();
                self.tlm_write_prm_statement_timeout_secs(value);
                valid
            }
            Self::PARAMID_SEQ_BASE_DIR => {
                let (value, valid) = self.param_get_seq_base_dir();
                let mut path = FileNameString::new();
                path.set_bytes(value.as_bytes());
                self.tlm_write_prm_seq_base_dir(&path);
                valid
            }
            _ => {
                // C++ parity: a parameter missing from the switch.
                fw_assert!(false, id as i32);
                ParamValid::Invalid
            }
        };
        fw_assert!(valid.is_ok(), valid.as_repr() as i32);
    }

    /// The generated `<PARAM>_PRM_SET` handler: deserialize the value (a
    /// leftover byte is a format error), store it as `VALID`, then call
    /// `parameterUpdated`.
    fn param_set(&self, id: FwPrmIdType, args: &mut CmdArgBuffer) -> CmdResponse {
        match id {
            Self::PARAMID_STATEMENT_TIMEOUT_SECS => {
                let mut value = 0f32;
                if !args.deserialize_f32_be(&mut value).is_ok() || args.deserialize_size_left() != 0
                {
                    return CmdResponse::FormatError;
                }
                let mut params = self.params.lock().unwrap();
                params.statement_timeout_secs = value;
                params.statement_timeout_secs_valid = ParamValid::Valid;
            }
            _ => {
                let mut value = ParamString::new();
                if !args.deserialize(&mut value, Endianness::Big).is_ok()
                    || args.deserialize_size_left() != 0
                {
                    return CmdResponse::FormatError;
                }
                let mut params = self.params.lock().unwrap();
                params.seq_base_dir = value;
                params.seq_base_dir_valid = ParamValid::Valid;
            }
        }
        self.parameter_updated(id);
        CmdResponse::Ok
    }

    /// The generated `<PARAM>_PRM_SAVE` handler: push the current value to
    /// the parameter database through `prmSet`.
    fn param_save(&self, id: FwPrmIdType, args: &CmdArgBuffer) -> CmdResponse {
        if args.deserialize_size_left() != 0 {
            return CmdResponse::FormatError;
        }
        if !self.prm.prm_set_out.is_connected() {
            return CmdResponse::ExecutionError;
        }
        let mut buf = ParamBuffer::new();
        let status = {
            let params = self.params.lock().unwrap();
            if id == Self::PARAMID_STATEMENT_TIMEOUT_SECS {
                buf.serialize_f32_be(params.statement_timeout_secs)
            } else {
                params.seq_base_dir.serialize_to(&mut buf, Endianness::Big)
            }
        };
        fw_assert!(status.is_ok(), status as i32);
        self.prm.set_param(self.id_base(), id, &mut buf);
        CmdResponse::Ok
    }
}

