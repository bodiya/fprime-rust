impl FpySequencer {
    fn reject_command(&self, op_code: FwOpcodeType, cmd_seq: u32) {
        self.log_warning_hi_invalid_command(self.sequencer_get_state().as_repr() as i32);
        self.cmd
            .cmd_response(op_code, cmd_seq, CmdResponse::ExecutionError);
    }

    /// `RUN_cmdHandler`: `RUN_ARGS` with empty arguments.
    fn run_cmd_handler(
        &self,
        op_code: FwOpcodeType,
        cmd_seq: u32,
        file_name: &CmdStringArg,
        block: BlockState,
    ) {
        self.run_args_cmd_handler(op_code, cmd_seq, file_name, block, &SeqArgs::default());
    }

    /// `RUN_ARGS_cmdHandler`.
    fn run_args_cmd_handler(
        &self,
        op_code: FwOpcodeType,
        cmd_seq: u32,
        file_name: &CmdStringArg,
        block: BlockState,
        args: &SeqArgs,
    ) {
        // can only run a seq while in idle
        if self.sequencer_get_state() != State::IDLE {
            self.reject_command(op_code, cmd_seq);
            return;
        }
        if block == BlockState::Block {
            let mut st = self.state.lock().unwrap();
            st.saved_op_code = op_code;
            st.saved_cmd_seq = cmd_seq;
        }
        let mut path = FileNameString::new();
        path.set_bytes(file_name.as_bytes());
        self.sm()
            .send_signal_cmd_RUN(&SequenceExecutionArgs::new(path, block, *args));
        // only respond if the user doesn't want us to block further execution
        if block == BlockState::NoBlock {
            self.cmd.cmd_response(op_code, cmd_seq, CmdResponse::Ok);
        }
    }

    /// `VALIDATE_cmdHandler`: `VALIDATE_ARGS` with empty arguments.
    fn validate_cmd_handler(&self, op_code: FwOpcodeType, cmd_seq: u32, file_name: &CmdStringArg) {
        self.validate_args_cmd_handler(op_code, cmd_seq, file_name, &SeqArgs::default());
    }

    /// `VALIDATE_ARGS_cmdHandler`.
    fn validate_args_cmd_handler(
        &self,
        op_code: FwOpcodeType,
        cmd_seq: u32,
        file_name: &CmdStringArg,
        buffer: &SeqArgs,
    ) {
        if self.sequencer_get_state() != State::IDLE {
            self.reject_command(op_code, cmd_seq);
            return;
        }
        {
            // validate always blocks until finished
            let mut st = self.state.lock().unwrap();
            st.saved_op_code = op_code;
            st.saved_cmd_seq = cmd_seq;
        }
        let mut path = FileNameString::new();
        path.set_bytes(file_name.as_bytes());
        self.sm()
            .send_signal_cmd_VALIDATE(&SequenceExecutionArgs::new(
                path,
                BlockState::Block,
                *buffer,
            ));
    }

    /// `RUN_VALIDATED_cmdHandler`.
    fn run_validated_cmd_handler(&self, op_code: FwOpcodeType, cmd_seq: u32, block: BlockState) {
        if self.sequencer_get_state() != State::AWAITING_CMD_RUN_VALIDATED {
            self.reject_command(op_code, cmd_seq);
            return;
        }
        let value = {
            let mut st = self.state.lock().unwrap();
            if block == BlockState::Block {
                st.saved_op_code = op_code;
                st.saved_cmd_seq = cmd_seq;
            }
            SequenceExecutionArgs::new(st.sequence_file_path.clone(), block, st.sequence_args)
        };
        self.sm().send_signal_cmd_RUN_VALIDATED(&value);
        if block == BlockState::NoBlock {
            self.cmd.cmd_response(op_code, cmd_seq, CmdResponse::Ok);
        }
    }

    /// `CANCEL_cmdHandler`: valid in every state but `IDLE`; answers at once.
    fn cancel_cmd_handler(&self, op_code: FwOpcodeType, cmd_seq: u32) {
        if self.sequencer_get_state() == State::IDLE {
            self.reject_command(op_code, cmd_seq);
            return;
        }
        self.sm().send_signal_cmd_CANCEL();
        self.cmd.cmd_response(op_code, cmd_seq, CmdResponse::Ok);
    }

    /// `SET_BREAKPOINT_cmdHandler`: valid in every state.
    fn set_breakpoint_cmd_handler(
        &self,
        op_code: FwOpcodeType,
        cmd_seq: u32,
        stmt_idx: u32,
        break_once: bool,
    ) {
        self.sm()
            .send_signal_cmd_SET_BREAKPOINT(&BreakpointArgs::new(true, break_once, stmt_idx));
        self.cmd.cmd_response(op_code, cmd_seq, CmdResponse::Ok);
    }

    /// `BREAK_cmdHandler`: valid in the running substates but `PAUSED`.
    fn break_cmd_handler(&self, op_code: FwOpcodeType, cmd_seq: u32) {
        let state = self.sequencer_get_state();
        if !Self::is_running_state(state) || state == State::RUNNING_PAUSED {
            self.reject_command(op_code, cmd_seq);
            return;
        }
        self.sm().send_signal_cmd_BREAK();
        self.cmd.cmd_response(op_code, cmd_seq, CmdResponse::Ok);
    }

    /// `CONTINUE_cmdHandler`: valid in `RUNNING_PAUSED` only.
    fn continue_cmd_handler(&self, op_code: FwOpcodeType, cmd_seq: u32) {
        if self.sequencer_get_state() != State::RUNNING_PAUSED {
            self.reject_command(op_code, cmd_seq);
            return;
        }
        self.sm().send_signal_cmd_CONTINUE();
        self.cmd.cmd_response(op_code, cmd_seq, CmdResponse::Ok);
    }

    /// `CLEAR_BREAKPOINT_cmdHandler`: valid in every state. C++ parity: the
    /// `BreakpointCleared` event is emitted here, before the signal is
    /// handled.
    fn clear_breakpoint_cmd_handler(&self, op_code: FwOpcodeType, cmd_seq: u32) {
        self.sm().send_signal_cmd_CLEAR_BREAKPOINT();
        self.log_activity_hi_breakpoint_cleared();
        self.cmd.cmd_response(op_code, cmd_seq, CmdResponse::Ok);
    }

    /// `STEP_cmdHandler`: valid in `RUNNING_PAUSED` only.
    fn step_cmd_handler(&self, op_code: FwOpcodeType, cmd_seq: u32) {
        if self.sequencer_get_state() != State::RUNNING_PAUSED {
            self.reject_command(op_code, cmd_seq);
            return;
        }
        self.sm().send_signal_cmd_STEP();
        self.cmd.cmd_response(op_code, cmd_seq, CmdResponse::Ok);
    }

    /// `DUMP_STACK_TO_FILE_cmdHandler`: valid in `RUNNING_PAUSED` only;
    /// writes the stack bytes to `file_name`.
    fn dump_stack_to_file_cmd_handler(
        &self,
        op_code: FwOpcodeType,
        cmd_seq: u32,
        file_name: &CmdStringArg,
    ) {
        if self.sequencer_get_state() != State::RUNNING_PAUSED {
            self.reject_command(op_code, cmd_seq);
            return;
        }
        let path = String::from_utf8_lossy(file_name.as_bytes());
        let mut file = File::new();
        let status = file.open(&path, FileMode::OpenWrite);
        if status != FileStatus::OpOk {
            self.log_warning_hi_file_open_error(file_name.as_bytes(), status as i32);
            self.cmd
                .cmd_response(op_code, cmd_seq, CmdResponse::ExecutionError);
            return;
        }
        let st = self.state.lock().unwrap();
        let stack_size = st.runtime.stack.size;
        let mut write_size = FwSizeType::from(stack_size);
        let status = file.write(
            &st.runtime.stack.bytes[..stack_size as usize],
            &mut write_size,
            WaitType::Wait,
        );
        drop(st);
        if status != FileStatus::OpOk || write_size != FwSizeType::from(stack_size) {
            self.log_warning_hi_file_write_error(write_size, file_name.as_bytes(), status as i32);
            self.cmd
                .cmd_response(op_code, cmd_seq, CmdResponse::ExecutionError);
            return;
        }
        self.cmd.cmd_response(op_code, cmd_seq, CmdResponse::Ok);
    }

    /// The generated async command dispatch: deserialize the arguments in
    /// declaration order (`FORMAT_ERROR` on a failure or a leftover byte,
    /// `VALIDATION_ERROR` on an undeclared enum value) and call the handler.
    fn cmd_in_handler(
        &self,
        _port_num: FwIndexType,
        op_code: FwOpcodeType,
        cmd_seq: u32,
        args: &mut CmdArgBuffer,
    ) {
        let respond = |response| self.cmd.cmd_response(op_code, cmd_seq, response);
        let local = op_code.wrapping_sub(self.id_base());
        let mut file_name = CmdStringArg::new();
        if matches!(
            local,
            Self::OPCODE_RUN
                | Self::OPCODE_RUN_ARGS
                | Self::OPCODE_VALIDATE
                | Self::OPCODE_VALIDATE_ARGS
                | Self::OPCODE_DUMP_STACK_TO_FILE
        ) && !args.deserialize(&mut file_name, Endianness::Big).is_ok()
        {
            respond(CmdResponse::FormatError);
            return;
        }
        let mut block = BlockState::default();
        if matches!(
            local,
            Self::OPCODE_RUN | Self::OPCODE_RUN_ARGS | Self::OPCODE_RUN_VALIDATED
        ) {
            let mut raw = 0u8;
            if !args.deserialize_u8_be(&mut raw).is_ok() {
                respond(CmdResponse::FormatError);
                return;
            }
            match BlockState::try_from(raw) {
                Ok(b) => block = b,
                Err(_) => {
                    respond(CmdResponse::ValidationError);
                    return;
                }
            }
        }
        let mut seq_args = SeqArgs::default();
        if matches!(local, Self::OPCODE_RUN_ARGS | Self::OPCODE_VALIDATE_ARGS)
            && !args.deserialize(&mut seq_args, Endianness::Big).is_ok()
        {
            respond(CmdResponse::FormatError);
            return;
        }
        let mut stmt_idx = 0u32;
        let mut break_once = false;
        if local == Self::OPCODE_SET_BREAKPOINT
            && (!args.deserialize_u32_be(&mut stmt_idx).is_ok()
                || !args.deserialize_bool_be(&mut break_once).is_ok())
        {
            respond(CmdResponse::FormatError);
            return;
        }
        if args.deserialize_size_left() != 0 {
            respond(CmdResponse::FormatError);
            return;
        }
        match local {
            Self::OPCODE_RUN => self.run_cmd_handler(op_code, cmd_seq, &file_name, block),
            Self::OPCODE_RUN_ARGS => {
                self.run_args_cmd_handler(op_code, cmd_seq, &file_name, block, &seq_args);
            }
            Self::OPCODE_VALIDATE => self.validate_cmd_handler(op_code, cmd_seq, &file_name),
            Self::OPCODE_VALIDATE_ARGS => {
                self.validate_args_cmd_handler(op_code, cmd_seq, &file_name, &seq_args);
            }
            Self::OPCODE_RUN_VALIDATED => self.run_validated_cmd_handler(op_code, cmd_seq, block),
            Self::OPCODE_CANCEL => self.cancel_cmd_handler(op_code, cmd_seq),
            Self::OPCODE_SET_BREAKPOINT => {
                self.set_breakpoint_cmd_handler(op_code, cmd_seq, stmt_idx, break_once);
            }
            Self::OPCODE_BREAK => self.break_cmd_handler(op_code, cmd_seq),
            Self::OPCODE_CONTINUE => self.continue_cmd_handler(op_code, cmd_seq),
            Self::OPCODE_CLEAR_BREAKPOINT => self.clear_breakpoint_cmd_handler(op_code, cmd_seq),
            Self::OPCODE_STEP => self.step_cmd_handler(op_code, cmd_seq),
            Self::OPCODE_DUMP_STACK_TO_FILE => {
                self.dump_stack_to_file_cmd_handler(op_code, cmd_seq, &file_name);
            }
            _ => respond(CmdResponse::InvalidOpcode),
        }
    }

    /// `cmdIn` — the command port factory for wiring.
    pub fn cmd_in(self: &Arc<Self>, port_num: FwIndexType) -> PortRef<dyn CmdPort> {
        PortRef::new(self.clone(), port_num)
    }
}

impl CmdPort for FpySequencer {
    /// The generated `cmdIn` handler: the parameter commands run here, on
    /// the caller's thread; every other command is queued with its FPP
    /// priority (`CANCEL` 8, the rest 7) and the `assert` policy.
    fn invoke(
        &self,
        port_num: FwIndexType,
        op_code: FwOpcodeType,
        cmd_seq: u32,
        args: &mut CmdArgBuffer,
    ) {
        let local = op_code.wrapping_sub(self.id_base());
        let response = match local {
            Self::OPCODE_STATEMENT_TIMEOUT_SECS_PRM_SET => {
                Some(self.param_set(Self::PARAMID_STATEMENT_TIMEOUT_SECS, args))
            }
            Self::OPCODE_STATEMENT_TIMEOUT_SECS_PRM_SAVE => {
                Some(self.param_save(Self::PARAMID_STATEMENT_TIMEOUT_SECS, args))
            }
            Self::OPCODE_SEQ_BASE_DIR_PRM_SET => {
                Some(self.param_set(Self::PARAMID_SEQ_BASE_DIR, args))
            }
            Self::OPCODE_SEQ_BASE_DIR_PRM_SAVE => {
                Some(self.param_save(Self::PARAMID_SEQ_BASE_DIR, args))
            }
            Self::OPCODE_RUN..=Self::OPCODE_DUMP_STACK_TO_FILE => None,
            _ => Some(CmdResponse::InvalidOpcode),
        };
        if let Some(response) = response {
            self.cmd.cmd_response(op_code, cmd_seq, response);
            return;
        }
        let priority = if local == Self::OPCODE_CANCEL {
            CANCEL_PRIORITY
        } else {
            CMD_PRIORITY
        };
        let mut buf = LinearBuffer::<QUEUE_MSG_SIZE>::new();
        let status = msg::write_envelope_header(&mut buf, Self::MSG_TYPE_CMD_IN, port_num);
        fw_assert!(status.is_ok(), status as i32);
        let status = buf.serialize_u32_be(op_code);
        fw_assert!(status.is_ok(), status as i32);
        let status = buf.serialize_u32_be(cmd_seq);
        fw_assert!(status.is_ok(), status as i32);
        let status = buf.serialize_buffer(args, Endianness::Big);
        fw_assert!(status.is_ok(), status as i32);
        let _ = self
            .active
            .queued
            .send_message(&buf, priority, QueueFullPolicy::Assert);
    }
}

