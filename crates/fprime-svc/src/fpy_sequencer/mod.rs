impl FpySequencer {
    /// `checkTimers_handler`.
    fn check_timers_handler(&self, _port_num: FwIndexType, _context: u32) {
        self.sm().send_signal_checkTimersIn();
    }

    /// `pingIn_handler`.
    fn ping_in_handler(&self, _port_num: FwIndexType, key: u32) {
        let p = self.ping_out.get();
        p.target.invoke(p.port_num, key);
    }

    /// `cmdResponseIn_handler`: match a command response against the
    /// statement that sent it (sequence and statement indices in the
    /// command UID, the opcode), then push the response code.
    fn cmd_response_in_handler(
        &self,
        _port_num: FwIndexType,
        op_code: FwOpcodeType,
        cmd_seq: u32,
        response: CmdResponse,
    ) {
        let state = self.sequencer_get_state();
        // not running: a CANCEL while a command was out (nominal), or a
        // misbehaving component. Report, do not fail anything.
        if !Self::is_running_state(state) {
            self.log_warning_lo_cmd_response_while_not_running_sequence(
                state.as_repr() as i32,
                get_event_opcode(op_code),
                response,
            );
            return;
        }
        // the cmdSeq argument is the context we sent, the command UID
        let cmd_uid = cmd_seq;
        let sequence_index = ((cmd_uid & 0xFFFF_0000) >> 16) as u16;
        let mut st = self.state.lock().unwrap();
        let current_sequence_index = (st.sequences_started & 0xFFFF) as u16;
        if sequence_index != current_sequence_index {
            self.log_warning_lo_cmd_response_from_old_sequence(
                get_event_opcode(op_code),
                response,
                sequence_index,
                current_sequence_index,
            );
            return;
        }
        // from this sequence: anything wrong from here fails the sequence
        if state != State::RUNNING_AWAITING_STATEMENT_RESPONSE {
            self.log_warning_hi_cmd_response_while_not_awaiting(
                get_event_opcode(op_code),
                response,
            );
            self.sm().send_signal_stmtResponse_unexpected();
            return;
        }
        let current = st.runtime.current_statement_opcode;
        if current != DirectiveId::ConstCmd.as_repr() && current != DirectiveId::StackCmd.as_repr()
        {
            self.log_warning_hi_cmd_response_while_awaiting_directive(
                get_event_opcode(op_code),
                response,
                current,
            );
            self.sm().send_signal_stmtResponse_unexpected();
            return;
        }
        if op_code != st.runtime.current_cmd_opcode {
            self.log_warning_hi_wrong_cmd_response_opcode(
                get_event_opcode(op_code),
                response,
                get_event_opcode(st.runtime.current_cmd_opcode),
            );
            self.sm().send_signal_stmtResponse_unexpected();
            return;
        }
        let cmd_index = (cmd_uid & 0xFFFF) as u16;
        // a statement has definitely been dispatched by now
        fw_assert!(st.statements_dispatched > 0);
        let current_cmd_index = (st.statements_dispatched & 0xFFFF) as u16;
        if cmd_index != current_cmd_index {
            self.log_warning_hi_wrong_cmd_response_index(
                get_event_opcode(op_code),
                response,
                cmd_index,
                current_cmd_index,
            );
            self.sm().send_signal_stmtResponse_unexpected();
            return;
        }
        // always succeed; the sequence can branch on the pushed response
        self.sm().send_signal_stmtResponse_success();
        // the constCmd/stackCmd handlers made room for this push
        st.runtime.stack.push(response.as_repr());
    }

    /// `seqCancelIn_handler`.
    fn seq_cancel_in_handler(&self, _port_num: FwIndexType) {
        let state = self.sequencer_get_state();
        if state == State::IDLE {
            self.log_warning_hi_invalid_seq_cancel_call(state.as_repr() as i32);
            return;
        }
        self.sm().send_signal_cmd_CANCEL();
    }

    /// `seqRunIn_handler`: never blocking.
    fn seq_run_in_handler(
        &self,
        _port_num: FwIndexType,
        filename: &FileNameString,
        args: &SeqArgs,
    ) {
        let state = self.sequencer_get_state();
        if state != State::IDLE {
            self.log_warning_hi_invalid_seq_run_call(state.as_repr() as i32);
            return;
        }
        self.sm().send_signal_cmd_RUN(&SequenceExecutionArgs::new(
            filename.clone(),
            BlockState::NoBlock,
            *args,
        ));
    }

    /// `tlmWrite_handler`: write every channel but the two parameter
    /// echoes.
    fn tlm_write_handler(&self, _port_num: FwIndexType, _context: u32) {
        let state = self.sequencer_get_state();
        self.tlm_write_state(state.as_repr() as FwEnumStoreType);
        let mut st = self.state.lock().unwrap();
        self.tlm_write_statements_dispatched(st.statements_dispatched);
        self.tlm_write_statements_failed(st.tlm.statements_failed);
        self.tlm_write_sequences_cancelled(st.tlm.sequences_cancelled);
        self.tlm_write_sequences_succeeded(st.tlm.sequences_succeeded);
        self.tlm_write_sequences_failed(st.tlm.sequences_failed);
        self.tlm_write_last_directive_error(st.tlm.last_directive_error);
        self.tlm_write_directive_error_index(st.tlm.directive_error_index);
        self.tlm_write_directive_error_id(st.tlm.directive_error_id);
        self.tlm_write_seq_path(&st.sequence_file_path);

        self.tlm_write_breakpoint_index(st.breakpoint.breakpoint_index);
        self.tlm_write_break_only_once_on_breakpoint(st.breakpoint.break_only_once_on_breakpoint);
        self.tlm_write_break_before_next_line(st.breakpoint.break_before_next_line);
        self.tlm_write_breakpoint_in_use(st.breakpoint.breakpoint_in_use);

        self.update_debug_telemetry_struct(&mut st);
        let debug = st.debug;
        drop(st);
        self.tlm_write_debug_next_cmd_opcode(debug.next_cmd_opcode);
        self.tlm_write_debug_next_statement_opcode(debug.next_statement_opcode);
        self.tlm_write_debug_next_statement_read_success(debug.next_statement_read_success);
        self.tlm_write_debug_next_statement_index(debug.next_statement_index);
        self.tlm_write_debug_reached_end_of_file(debug.reached_end_of_file);
        self.tlm_write_debug_stack_size(debug.stack_size);
    }

    /// C++ `updateDebugTelemetryStruct`: describe the next statement while
    /// paused, defaults otherwise.
    fn update_debug_telemetry_struct(&self, st: &mut FpyState) {
        if self.sequencer_get_state() == State::RUNNING_PAUSED {
            let next = st.runtime.next_statement_index;
            let stack_size = st.runtime.stack.size;
            if next >= u32::from(st.sequence_obj.header.statement_count) {
                st.debug = DebugInfo {
                    reached_end_of_file: true,
                    next_statement_read_success: false,
                    next_statement_opcode: 0,
                    next_cmd_opcode: 0,
                    next_statement_index: next,
                    stack_size,
                };
                return;
            }
            fw_assert!(
                (next as usize) < st.sequence_obj.statements.len(),
                next as i32
            );
            let next_stmt = &st.sequence_obj.statements[next as usize];
            let opcode = next_stmt.op_code.as_repr();
            let directive = self.deserialize_directive(st, next_stmt);
            st.debug = match directive {
                None => DebugInfo {
                    reached_end_of_file: false,
                    next_statement_read_success: false,
                    next_statement_opcode: opcode,
                    next_cmd_opcode: 0,
                    next_statement_index: next,
                    stack_size,
                },
                Some(DirectiveUnion::ConstCmd(cmd)) => DebugInfo {
                    reached_end_of_file: false,
                    next_statement_read_success: true,
                    next_statement_opcode: opcode,
                    next_cmd_opcode: cmd.op_code,
                    next_statement_index: next,
                    stack_size,
                },
                Some(_) => DebugInfo {
                    reached_end_of_file: false,
                    next_statement_read_success: true,
                    next_statement_opcode: opcode,
                    next_cmd_opcode: 0,
                    next_statement_index: next,
                    stack_size,
                },
            };
            return;
        }
        st.debug = DebugInfo::default();
    }
}

