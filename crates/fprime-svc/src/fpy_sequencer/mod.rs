//! # FpySequencer — port of `Svc::FpySequencer` (active)
//!
//! C++ sources: `Svc/FpySequencer/FpySequencer.{fpp,hpp,cpp}`,
//! `FpySequencer{Commands,Events,Telemetry,Params,Directives}.fppi`,
//! `FpySequencerTypes.fpp`, `FpySequencerStateMachine.{fppi,cpp}`,
//! `FpySequencerValidationState.cpp` ([`validation`]),
//! `FpySequencerRunState.cpp` ([`run_state`]),
//! `FpySequencerDirectives.cpp` ([`directives`]),
//! `FpySequencerStack.cpp` ([`Stack`]), `Fw/Fpy/StatementArgBuffer`,
//! `default/config/FpySequencerCfg.fpp` ([`fprime_config::fpy_sequencer`]).
//! Documentation: `Svc/FpySequencer/docs/{sdd,directives}.md`.
//!
//! Loads, validates and runs one Fpy sequence at a time: a binary file
//! (header, argument specs, statements, CRC-32 footer) whose statements are
//! the directives of a small stack machine — arithmetic and comparisons on
//! a byte stack, branches, function calls, waits, telemetry and parameter
//! reads, events, serial output and command dispatch.
//!
//! The sequencer is the FPP state machine `SequencerStateMachine`
//! ([`StateMachine`], generated by `fprime_comp::fpp_state_machine!`; its
//! traces are checked against the reference compiler's C++ by
//! `tests/fpy_sequencer_sm_traces.rs`):
//!
//! ```text
//! IDLE --cmd_RUN/cmd_VALIDATE--> VALIDATING --result_success--> (VALID)
//!   (VALID) --goal RUNNING--> RUNNING | else --> AWAITING_CMD_RUN_VALIDATED
//! RUNNING { BREAK_CHECK -> DISPATCH_STATEMENT -> AWAITING_STATEMENT_RESPONSE
//!           -> (SLEEPING | BREAK_CHECK) ; PAUSED on a breakpoint }
//! ```
//!
//! Every input — commands, ports, the state machine's own signals and the
//! directives — is a message on the component queue, with the upstream
//! priorities: ping 10, state machine signals 9, `CANCEL` and
//! `seqCancelIn` 8, the other commands and `seqRunIn` 7, directives 6,
//! command responses 5, `checkTimers` 4, `tlmWrite` 1. A statement is
//! dispatched by deserializing its directive and sending it to the
//! directive's internal port (`directive_*`); the handler runs the
//! directive on the component thread and answers the state machine with a
//! `stmtResponse_*` signal.
//!
//! Commands sent by a sequence (`CONST_CMD`, `STACK_CMD`) carry a command
//! UID in their context: `(sequencesStarted & 0xFFFF) << 16 |
//! (statementsDispatched & 0xFFFF)`; `cmdResponseIn` uses it to tell a
//! response for this statement from a stale or foreign one, then pushes the
//! response code onto the stack.
//!
//! Threading: ACTIVE. Component state lives in one `Mutex` touched only on
//! the component thread (the C++ component is single-threaded); state
//! machine actions lock it for their own duration. The parameter commands
//! are synchronous, as the generated C++ handles them, and use their own
//! lock.

